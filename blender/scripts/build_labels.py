"""Printed-stock card, clear ticket-window, clip and shelf-rail assemblies."""
from hero_utils import box, quad, cylinder

LABEL_IDS=("G","Y","O","R")


def build(b):
    c=b.collection("03 · EXPIRY-WARNING LABELS")
    white=b.mat("Ticket card · uncoated warm white","#FAF7EE",.78)
    steel=b.materials["arch_dark"]; brass=b.materials["arch_brass"]
    clear=b.mat("Label window · clear acrylic","#EAF3EC",.105,.025,transmission=.88,ior=1.49,coat=.35)
    color_order=("G","Y","O","R","G","Y","O","R","G","Y","O","R","G","Y","O")
    for ri,y in enumerate(b.shelf_rows):
        for li,z in enumerate(b.shelf_levels):
            # One compact price ticket for each assortment bay. The featured
            # group uses the configured G/Y/O/R progression and is centred.
            xs=[-7.8,-5.2,-2.6,0,2.6,5.2,7.8]
            if ri==0 and li==1:
                xs=[-7.8,-5.2,-1.62,-.54,.54,1.62,5.2,7.8]
            for idx,x in enumerate(xs):
                colour_id=(LABEL_IDS[idx-2] if ri==0 and li==1 and 2<=idx<=5 else color_order[(idx+li+ri)%len(color_order)])
                is_feature=ri==0 and li==1 and 2<=idx<=5
                # A brushed aluminium sub-rail is visibly proud of the shelf lip.
                cassette=box(f"Label ticket cassette · {ri+1}-{li+1}-{idx+1}",(x,y-.61,z+.055),(.91,.07,.34),steel,collection=c,bevel=.025,web=ri==0 and abs(x)<4.1)
                cassette["label_feature"]=is_feature
                substrate=box(f"Paper card substrate · {ri+1}-{li+1}-{idx+1}",(x,y-.652,z+.057),(.875,.018,.296),white,collection=c,bevel=.008,web=ri==0 and abs(x)<4.1)
                substrate["label_feature"]=is_feature
                image_material=b.image_mat(f"Printed ticket artwork · {colour_id}","shelf_label",LABEL_IDS.index(colour_id),roughness=.7,bump_strength=0)
                name=(f"Q3_LABEL_{colour_id}_PANEL" if is_feature else f"Ticket artwork · {colour_id} · {ri+1}-{li+1}-{idx+1}")
                panel=quad(name,(x,y-.665,z+.057),.846,.282,image_material,collection=c,web=ri==0 and abs(x)<4.1)
                panel["colour_id"]=colour_id; panel["target_srgb_hex"]=b.config["colours"][colour_id]["hex"]
                panel["printed_label_artwork"]="synthetic digital artwork; not measured printed stock"
                panel["label_feature"]=is_feature
                # The clear cover leaves the actual label face legible and adds edge reflections.
                # A minimal acrylic frame avoids an extra glass sheet obscuring fine text.
                for dx in (-.431,.431):
                    edge=box(f"Clear ticket cover edge · {ri+1}-{li+1}-{idx+1} · {dx}",(x+dx,y-.672,z+.057),(.014,.009,.286),clear,collection=c,bevel=.004,web=ri==0 and abs(x)<4.1)
                    edge["label_feature"]=is_feature
                for dx in (-.36,.36):
                    clip=box(f"Ticket retaining clip · {ri+1}-{li+1}-{idx+1} · {dx}",(x+dx,y-.681,z+.207),(.035,.025,.025),brass,collection=c,bevel=.006,web=ri==0 and abs(x)<4.1)
                    clip["label_feature"]=is_feature
                if is_feature:
                    b.web_label_names.add(panel.name)
    # Premium near-expiry callout on the main aisle upright at comfortable eye height.
    sign=b.materials["arch_sage"]
    box("Donate-now aisle plaque",(-8.65,-5.75,4.48),(2.35,.07,.53),sign,collection=c,bevel=.035,web=True)
    # Main warning swatch is the configured exact sRGB value stored as metadata.
    b.scene["expiry_warning_colour_hex"]=b.config["colours"]["R"]["hex"]
    b.scene["label_artwork_note"]="Synthetic visual ticket textures generated by generate_packaging_art.py; RGB presentation assets only, not printer or reflectance measurements."
